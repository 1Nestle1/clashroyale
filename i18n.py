def t(key: str, lang: str = "en", **kwargs) -> str:
    text = TRANSLATIONS.get(lang, TRANSLATIONS["en"]).get(key, TRANSLATIONS["en"].get(key, key))
    return text.format(**kwargs) if kwargs else text


def tt(key: str, sub: str, lang: str = "en") -> str:
    """Look up a sub-key inside a dict translation (e.g. rarity/type/attribute)."""
    table = TRANSLATIONS.get(lang, TRANSLATIONS["en"]).get(key, {})
    return table.get(sub, sub)


def detect_lang(user) -> str:
    code = (getattr(user, "language_code", "") or "").lower()
    return "ru" if code.startswith("ru") else "en"
